o2, e2, t2, m2, c2, f2 = [na.nodes.new(k) for k in ("ShaderNodeOutputMaterial", "ShaderNodeEmission", "ShaderNodeBsdfTransparent", "ShaderNodeMixShader", "ShaderNodeAttribute", "ShaderNodeAttribute")]
c2.attribute_name = "col"; f2.attribute_name = "a"
na.links.new(c2.outputs["Color"], e2.inputs["Color"]); na.links.new(f2.outputs["Fac"], m2.inputs[0]); na.links.new(t2.outputs[0], m2.inputs[1]); na.links.new(e2.outputs[0], m2.inputs[2]); na.links.new(m2.outputs[0], o2.inputs["Surface"])
try: mat_a.surface_render_method = "BLENDED"
except Exception: mat_a.blend_method = "BLEND"


def world(px, py, depth):  # image px (origin top-left) -> Blender
    return (W / 2 - px, depth, H / 2 - py)          # the camera looks along -Y, which mirrors x, so flip it here


def layer_depth():
    _depth[0] += 0.05; return _depth[0]


def add_mesh(verts, faces, vcols, name):
    me = bpy.data.meshes.new(name); me.from_pydata(verts, [], faces); me.update()
    ca = me.color_attributes.new("col", "FLOAT_COLOR", "POINT")
    ca.data.foreach_set("color", np.concatenate([np.asarray(vcols), np.ones((len(vcols), 1))], 1).astype(np.float32).ravel())
    ob = bpy.data.objects.new(name, me); scn.collection.objects.link(ob); ob.data.materials.append(mat); return ob


def add_soft(pts_xy, faces, cols, alphas, name):
    """A soft shape: per-vertex colour and opacity. Drawn after the opaque layers, hidden by any nearer opaque layer."""
    d = layer_depth(); verts = [(W / 2 - x, 0.0, H / 2 - y) for x, y in pts_xy]
    me = bpy.data.meshes.new(name); me.from_pydata(verts, [], faces); me.update()
    ca = me.color_attributes.new("col", "FLOAT_COLOR", "POINT"); ca.data.foreach_set("color", np.concatenate([np.asarray(cols), np.ones((len(cols), 1))], 1).astype(np.float32).ravel())
    fa = me.attributes.new("a", "FLOAT", "POINT"); fa.data.foreach_set("value", np.asarray(alphas, np.float32))
    ob = bpy.data.objects.new(name, me); scn.collection.objects.link(ob); ob.location = (0, d, 0); ob.data.materials.append(mat_a); return ob


def strip(xs, ytop, ybot, ctop, cbot, name="strip", mod=None):
    """Fill between a top profile (per x) and a bottom profile. Colours are sRGB 0-255, blended top->bottom."""
    d = layer_depth(); n = len(xs); ybot = np.broadcast_to(ybot, xs.shape)
    verts = [world(x, y, d) for x, y in zip(xs, ytop)] + [world(x, y, d) for x, y in zip(xs, ybot)]
    m = np.ones(n) if mod is None else np.asarray(mod)
    cols = [lin(ctop) * m[i] for i in range(n)] + [lin(cbot) * m[i] for i in range(n)]
    faces = [(i, i + 1, n + i + 1, n + i) for i in range(n - 1)]
    return add_mesh(verts, faces, cols, name)


def poly(points, ctop, cbot, name="poly"):
    d = layer_depth(); pts = np.asarray(points, float); y0, y1 = pts[:, 1].min(), pts[:, 1].max()
    bm = bmesh.new(); vs = [bm.verts.new(world(x, y, d)) for x, y in pts]
    try: f = bm.faces.new(vs)
    except ValueError: bm.free(); return None
    bmesh.ops.triangulate(bm, faces=[f], quad_method="BEAUTY", ngon_method="EAR_CLIP")
    me = bpy.data.meshes.new(name); bm.to_mesh(me); bm.free()
    cols = []
    for v in me.vertices:
        y = H / 2 - v.co.z; t = 0 if y1 == y0 else (y - y0) / (y1 - y0); cols.append(lerp(lin(ctop), lin(cbot), t))
    ca = me.color_attributes.new("col", "FLOAT_COLOR", "POINT"); ca.data.foreach_set("color", np.concatenate([np.asarray(cols), np.ones((len(cols), 1))], 1).astype(np.float32).ravel())
    ob = bpy.data.objects.new(name, me); scn.collection.objects.link(ob); ob.data.materials.append(mat); return ob


def ribbon(po, pin, ctop, cbot, name="ribbon"):
    """A thin band between two polylines, drawn as quads (no triangulation surprises)."""
    d = layer_depth(); n = len(po); ys = np.array([p[1] for p in po]); y0, y1 = ys.min(), ys.max()
    verts = [world(x, y, d) for x, y in po] + [world(x, y, d) for x, y in pin]
    cols = [lerp(lin(ctop), lin(cbot), 0 if y1 == y0 else (y - y0) / (y1 - y0)) for y in ys] * 2
    return add_mesh(verts, [(i, i + 1, n + i + 1, n + i) for i in range(n - 1)], cols, name)


def glow(cx, cy, rx, ry, col, a0, power=1.7, rings=9, segs=40, name="glow"):
    """A soft radial glow or shadow: opaque-ish in the middle, fading to nothing at the edge."""
    pts = [(cx, cy)]; cols = [lin(col)]; al = [a0]
    for k in range(1, rings + 1):
        f = k / rings
        for j in range(segs):
            t = 2 * math.pi * j / segs; pts.append((cx + math.cos(t) * rx * f, cy + math.sin(t) * ry * f)); cols.append(lin(col)); al.append(a0 * (1 - f) ** power)
    faces = [(0, 1 + j, 1 + (j + 1) % segs) for j in range(segs)]
    for ring in range(rings - 1):
        for j in range(segs):
            a_, b_ = 1 + ring * segs + j, 1 + ring * segs + (j + 1) % segs; faces.append((a_, b_, b_ + segs, a_ + segs))
    return add_soft(pts, faces, cols, al, name)


def fogband(xs, ycen, up, down, col, peak, name="mist"):
    """A band of mist: transparent above, densest along ycen, transparent below. ycen can vary along x."""
    n = len(xs); ycen = np.broadcast_to(ycen, xs.shape); pts = [(x, y - up) for x, y in zip(xs, ycen)] + [(x, y) for x, y in zip(xs, ycen)] + [(x, y + down) for x, y in zip(xs, ycen)]
    cols = [lin(col)] * (3 * n); al = [0.0] * n + [peak] * n + [0.0] * n
    faces = [(i, i + 1, n + i + 1, n + i) for i in range(n - 1)] + [(n + i, n + i + 1, 2 * n + i + 1, 2 * n + i) for i in range(n - 1)]
    return add_soft(pts, faces, cols, al, name)


def blob(cx, cy, rx, ry, n=20, jit=0.0, seed=0):
    r = np.random.default_rng(seed); a = np.linspace(0, 2 * np.pi, n, endpoint=False); k = 1 + r.normal(0, jit, n)
    return np.stack([cx + np.cos(a) * rx * k, cy + np.sin(a) * ry * k], 1)


# ───────────── tall slender pines: tiers of drooping boughs, leaning with the wind ─────────────
def pine(cx_, base_y, height, width, ctop, cbot, tiers=9, seed=0, lean=.05):
    r = np.random.default_rng(seed); top = base_y - height; y_first = top; step = height * .70 / tiers
    left = [(cx_, top)]; right = []
    for k in range(tiers):
        f = (k + 1) / tiers; wk = width * (.18 + .82 * f ** .85) * r.uniform(.92, 1.08); yk = y_first + step * (k + 1) * 1.12 + height * .04
        left += [(cx_ - wk, yk + step * .62), (cx_ - wk * .24, yk - step * .26)]; right += [(cx_ + wk, yk + step * .62), (cx_ + wk * .24, yk - step * .26)]
    trunk_top = y_first + step * tiers * 1.12 + height * .04 + step * .3
    outline = left + [(cx_ - width * .04, trunk_top), (cx_ - width * .03, base_y), (cx_ + width * .03, base_y), (cx_ + width * .04, trunk_top)] + right[::-1]
    outline = [(x + WIND * lean * (base_y - y) * (1 if True else 0), y) for x, y in outline]                          # the tips lean downwind
    poly(outline, ctop, cbot, "pine")


