"""The Climb, drawn as stacked flat layers in the style of the reference: a pale sun and a colossal mountain in climate zones, seven bands of jagged tree-line fading from pink
haze to dark purple (with clumps and tall emergent trees), dark foreground land, an S-curved river of reflective water with stepping stones, tall slender pines, and a
third-person climber. Mist, glows and shadows are soft (vertex alpha); everything leans with the wind that fills the red scarf. Every shape is generated by code and drawn by
Blender with an orthographic camera, so the layers can later move at different speeds for parallax.

    blender -b --python tools/blender/climb_layers.py        Output: lab/climb/layers_<SCENE>.png     Environment: CV_ROOT, SCENE (base), W, HGT"""
