# ───────────── the colossal mountain: climate zones with ragged borders, pale and flat ─────────────
def massif(cx, half, top, base_y, seed):
    r = np.random.default_rng(seed); xs = np.linspace(cx - half, cx + half, 300); t = np.abs(xs - cx) / half
    noise = np.convolve(r.normal(0, 1, len(xs)), np.ones(7) / 7, "same")
    ridge = top + (base_y - top) * np.power(t, .86) + noise * 22 * (1 - t * .6) + 10 * np.sin(xs * .017 + seed)
    ridge = np.clip(ridge, top, base_y)
    def border(y0, k): return y0 + np.convolve(np.random.default_rng(seed + k).normal(0, 1, len(xs)), np.ones(9) / 9, "same") * 34 + 22 * np.sin(xs * .011 + k)
    zones = [(None, (230, 212, 218), (212, 190, 200)), (border(H * .085, 1), (158, 126, 150), (150, 120, 146)), (border(H * .175, 2), (214, 150, 128), (196, 138, 124)), (border(H * .245, 3), (150, 130, 128), (172, 136, 132))]
    for j, (bd, ctop, cbot) in enumerate(zones):
        yt = ridge if bd is None else np.maximum(ridge, bd); strip(xs, yt, np.full_like(xs, base_y), fogged(ctop, .10 if j == 0 else .30), fogged(cbot, .22 if j == 0 else .40), "zone%d" % j)
    fogband(xs, base_y - H * .035, H * .16, H * .05, (226, 184, 188), .78, "mountain_mist")                  # the foot of the mountain vanishes in fog


