def lin(c):
    c = np.asarray(c, float) / 255.0
    return np.power(c, 2.2)


def lerp(a, b, t): return a + (b - a) * t


HAZE_RGB = np.array((196, 150, 162))


def fogged(c, f): return tuple(np.asarray(c, float) * (1 - f) + HAZE_RGB * f)       # pull a colour towards the pink haze, by the fraction f


# ───────────── drawing: opaque filled shapes and soft (alpha) glows, vertex-coloured, unlit ─────────────
_depth = [0.0]
mat = bpy.data.materials.new("flat"); mat.use_nodes = True; nt = mat.node_tree; nt.nodes.clear()
_o, _e, _a = nt.nodes.new("ShaderNodeOutputMaterial"), nt.nodes.new("ShaderNodeEmission"), nt.nodes.new("ShaderNodeAttribute")
_a.attribute_name = "col"; nt.links.new(_a.outputs["Color"], _e.inputs["Color"]); nt.links.new(_e.outputs["Emission"], _o.inputs["Surface"])

