# ───────────── the forest: seven bands of trees in clumps, with gaps and tall emergent trees; mist between the bands ─────────────
def tree_profile(xs, base, hmin, hmax, wmin, wmax, seed, undulate=18.0):
    r = np.random.default_rng(seed); y = base - undulate * (np.sin(xs * .0021 + seed) * .6 + np.sin(xs * .0057 + seed * 2) * .4)
    top = np.full_like(xs, 1e9); x = -30.0
    while x < W + 30:
        w = r.uniform(wmin, wmax) * (.7 + .8 * r.random() ** 2); c = x + w
        clump = .58 + .62 * (.5 + .5 * math.sin(c * .0085 + seed * 1.3) * math.sin(c * .0031 + seed * .7))               # groves taller than their surroundings
        h = r.uniform(hmin, hmax) * clump
        roll = r.random()
        if roll < .055: h *= r.uniform(1.8, 2.6); w *= 1.25                                                                # an emergent tree
        elif roll < .085: h *= .38                                                                                         # a gap
        tri = np.interp(xs, [c - w, c + .22 * w * WIND, c + w], [0, 1, 0], left=0, right=0)                               # apex leans downwind
        tiers = 1 - .24 * np.abs(((xs - c) / w * 3.0) % 1 - .5) * 2 * (tri > 0)
        top = np.minimum(top, y - h * tri * tiers); x += w * r.uniform(.9, 1.9)
    return np.minimum(top, y)


