def glow_disc(cx, cy, r_core, r_halo, col_core, col_edge, rings=28):
    d = layer_depth(); segs = 96; verts = [world(cx, cy, d)]; cols = [lin(col_core)]
    for k in range(1, rings + 1):
        t = k / rings; r = r_core + (r_halo - r_core) * t if k > 1 else r_core; c = lerp(np.array(col_core, float), np.array(col_edge, float), np.clip((r - r_core) / (r_halo - r_core), 0, 1) ** .6 if k > 1 else 0)
        for j in range(segs):
            ang = 2 * math.pi * j / segs; verts.append(world(cx + math.cos(ang) * r, cy + math.sin(ang) * r, d)); cols.append(lin(c))
    faces = [(0, 1 + j, 1 + (j + 1) % segs) for j in range(segs)]
    for ring in range(rings - 1):
        for j in range(segs):
            a_, b_ = 1 + ring * segs + j, 1 + ring * segs + (j + 1) % segs; faces.append((a_, b_, b_ + segs, a_ + segs))
    return add_mesh(verts, faces, cols, "sun")


